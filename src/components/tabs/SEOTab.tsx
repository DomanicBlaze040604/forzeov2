function QueryTable({ rows, showTrend }: { rows: EnrichedQuery[]; showTrend?: boolean }) {
  if (rows.length === 0) return <div className="text-center py-6 text-gray-400 text-sm">No data</div>;
  return (
    <div className="space-y-0.5">
      <div className={cn("grid gap-2 px-2 pb-1.5 border-b border-gray-100",
        showTrend ? "grid-cols-[1fr_60px_60px_40px]" : "grid-cols-[1fr_60px_60px]")}>
        {["Query","Clicks","CTR", ...(showTrend ? ["↑↓"] : [])].map(h => (
          <span key={h} className="text-[10px] font-semibold text-gray-400 uppercase tracking-wider text-right first:text-left">{h}</span>
        ))}
      </div>
      {rows.map((q, i) => (
        <div key={q.query} className={cn("grid gap-2 px-2 py-1.5 rounded-lg hover:bg-gray-50",
          showTrend ? "grid-cols-[1fr_60px_60px_40px]" : "grid-cols-[1fr_60px_60px]")}>
          <span className="text-xs text-gray-700 truncate flex items-center gap-1">
            <span className="text-[10px] text-gray-300 w-4">{i + 1}</span>
            {q.query}
            {q.isBrand && <span className="text-[10px] text-blue-500">●</span>}
          </span>
          <span className="text-xs font-semibold text-gray-900 tabular-nums text-right">{fmt(q.clicks)}</span>
          <span className="text-xs text-gray-500 tabular-nums text-right">{fmtCTR(q.ctr)}</span>
          {showTrend && (
            <span className="flex items-center justify-end">
              {q.trend === "up" && <TrendingUp className="h-3 w-3 text-emerald-500" />}
              {q.trend === "down" && <TrendingDown className="h-3 w-3 text-rose-500" />}
              {q.trend === "stable" && <Minus className="h-3 w-3 text-gray-300" />}
            </span>
          )}
        </div>
      ))}
    </div>
  );
}

