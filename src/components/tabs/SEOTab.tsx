function fmt(n: number) {
  if (n >= 1_000_000) return `${(n / 1_000_000).toFixed(1)}M`;
  if (n >= 1_000) return `${(n / 1_000).toFixed(1)}K`;
  return String(n);
}

function fmtDate(s: string) {
  const d = new Date(s + "T00:00:00");
  return d.toLocaleDateString("en-US", { month: "short", day: "numeric" });
}

function fmtPos(p: number) { return p > 0 ? p.toFixed(1) : "—"; }
function fmtCTR(c: number) { return `${c.toFixed(1)}%`; }

function truncatePage(url: string, max = 52) {
  try {
    const u = new URL(url);
    const path = u.pathname + u.search;
    return path.length > max ? path.slice(0, max) + "…" : path;
  } catch {
    return url.length > max ? url.slice(0, max) + "…" : url;
  }
}

function detectBrand(query: string, brandName: string): boolean {
  if (!brandName) return false;
  const bn = brandName.toLowerCase().replace(/[^a-z0-9]/g, "");
  const qn = query.toLowerCase().replace(/[^a-z0-9]/g, "");
  return qn.includes(bn) || bn.includes(qn.slice(0, Math.max(3, bn.length - 1)));
}

function deltaIcon(delta: number | null) {
  if (delta === null || delta === 0) return <Minus className="h-3 w-3 text-gray-400" />;
  if (delta > 0) return <ArrowUpRight className="h-3 w-3 text-emerald-500" />;
  return <ArrowDownRight className="h-3 w-3 text-rose-500" />;
}

