function RecoCard({ icon: Icon, color, title, body }: {
  icon: React.ElementType; color: string; title: string; body: string;
}) {
  const colorMap: Record<string, string> = {
    emerald: "bg-emerald-50 border-emerald-200/60 text-emerald-600",
    amber: "bg-amber-50 border-amber-200/60 text-amber-600",
    rose: "bg-rose-50 border-rose-200/60 text-rose-600",
    blue: "bg-blue-50 border-blue-200/60 text-blue-600",
    purple: "bg-purple-50 border-purple-200/60 text-purple-600",
  };
  const iconColorMap: Record<string, string> = {
    emerald: "bg-emerald-100", amber: "bg-amber-100", rose: "bg-rose-100",
    blue: "bg-blue-100", purple: "bg-purple-100",
  };
  return (
    <div className={cn("flex items-start gap-3 rounded-xl border p-3.5", colorMap[color])}>
      <div className={cn("p-2 rounded-lg flex-shrink-0 mt-0.5", iconColorMap[color])}>
        <Icon className="h-4 w-4" />
      </div>
      <div>
        <p className="text-xs font-bold mb-0.5">{title}</p>
        <p className="text-[11px] opacity-80 leading-relaxed">{body}</p>
      </div>
    </div>
  );
}
